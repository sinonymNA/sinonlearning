export function glyphs(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] || G[" "];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c] === "#") ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
    cx += 4 * scale;
  }
}
export const textW = (t: string, s = 1) => t.length * 4 * s - s;
export function centred(ctx: CanvasRenderingContext2D, text: string, cx: number, y: number, color: string, scale = 1) { glyphs(ctx, text, Math.round(cx - textW(text, scale) / 2), y, color, scale); }
