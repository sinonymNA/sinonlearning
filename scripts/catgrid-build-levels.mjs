// Pre-builds the Cat Grid level table (so the game never waits on the generator). Usage: node scripts/catgrid-build-levels.mjs [count=200]
// Every puzzle has exactly one solution and can be solved by the teachable techniques in engine.hint. Takes a few minutes for 200 levels.
import fs from "node:fs";
import { generate, encodePuzzle, countSolutions, logicSolvable } from "../arcade-server/catgrid/engine.mjs";
const count = +(process.argv[2] || 200), out = [], t0 = Date.now();
for (let level = 1; level <= count; level++) {
  const p = generate(level); if (countSolutions(p.regions, 2) !== 1 || !logicSolvable(p)) throw new Error("bad puzzle " + level);
  out.push(encodePuzzle(p)); if (level % 20 === 0) console.log(`level ${level}/${count} (${Math.round((Date.now() - t0) / 1000)}s)`);
}
fs.writeFileSync(new URL("../arcade-server/catgrid/levels.mjs", import.meta.url), `// Generated by scripts/catgrid-build-levels.mjs. Do not edit by hand.\nexport const LEVELS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${count} levels in ${Math.round((Date.now() - t0) / 1000)}s`);
